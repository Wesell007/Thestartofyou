add("status_ended_at", "pregnancy_loss + ended_at NULL (equivalent)", LMP, DUE, "pregnancy_loss", "NULL", "1", "CK:pregnancy_episodes_ended_at_status_check", plan=False)

out = []
w = out.append
w("-- 41B.1A-C1 C1.10 — Episode CHECK semantics (plan stage C1.10, exact list, plus equivalent boundary proofs). Generated by gen_c1_10.py.")
w("-- Every case in its own SAVEPOINT (accepted rows read back then rolled back), one explicit transaction, final ROLLBACK. No bypass.")
w("-- Inserts use synthetic user C (no episode) so the one-open unique index cannot fire; only the constraint under test can reject.")
w("\\set ON_ERROR_STOP 0")
w("\\set VERBOSITY verbose")
w("\\pset footer off")
w("\\echo === C1.10 start")
w("select now() as started_at, current_user, (select project_ref || ' / ' || run_label from public.c1_rehearsal_marker) as marker;")
w("BEGIN;")
w("SET LOCAL lock_timeout = '5s';")
w("\\echo === live CHECK definitions and nullability (read-only)")
w("select conname, pg_get_constraintdef(oid) as def, convalidated from pg_constraint where conrelid = 'public.pregnancy_episodes'::regclass and contype = 'c' order by conname;")
w("select column_name, is_nullable from information_schema.columns where table_schema = 'public' and table_name = 'pregnancy_episodes' and column_name in ('lmp_date','due_date','status','ended_at','expected_count') order by ordinal_position;")
w("select count(*) as c_episodes_before from public.pregnancy_episodes where user_id = '" + C + "';")
for n, c in enumerate(CASES, 1):
    rid = NEW(n)
    vals = f"lmp={c['lmp']} due={c['due']} status={c['status']} ended_at={c['ended']} expected_count={c['ec']}"
    w(f"\\echo ### CASE C10-{n:02d}|{c['rule']}|{c['desc']}|{vals}|{c['expect']}|{'plan' if c['plan'] else 'equivalent'}")
    w(f"savepoint sp{n};")
    w(f"insert into public.pregnancy_episodes (id, user_id, lmp_date, due_date, status, ended_at, expected_count) values ('{rid}', '{c['user']}', {c['lmp']}, {c['due']}, '{c['status']}', {c['ended']}, {c['ec']});")
