# Generates C1_10_check_matrix.sql: plan stage C1.10 cases (exact list) plus equivalent boundary proofs.
# Every case runs inside its own SAVEPOINT (accepted rows are read back, then the savepoint is rolled back), so the
# one-open partial unique index can never fire and only the constraint under test can reject. Final ROLLBACK.
C = "6e65487d-ddb0-43b6-a623-fb24b5318dab"   # user C has no episode, so open-status inserts never collide
A = "b09cd318-8f3e-4853-8d97-fc10267b3d69"
LMP = "date '2026-09-01'"
DUE = "date '2027-06-08'"                   # lmp + 280
ENDED = "timestamptz '2027-06-01T10:00:00Z'"
NEW = lambda n: f"00000000-0000-4c10-8000-00000000ca{n:02x}"

# (id, rule, description, columns dict, expect) expect: OK | CK:<constraint> | NN:<column>
CASES = []
def add(rule, desc, lmp, due, status, ended, expected_count, expect, user=C, plan=True):
    CASES.append(dict(rule=rule, desc=desc, lmp=lmp, due=due, status=status, ended=ended, ec=expected_count, expect=expect, user=user, plan=plan))

# Dates (plan: =lmp rejected; +300 accepted; +301 rejected) + equivalents (+1 accepted; before lmp rejected)
add("dates", "due_date = lmp_date (plan)", LMP, LMP, "active", "NULL", "1", "CK:pregnancy_episodes_dates_check")
add("dates", "due_date = lmp_date + 300 (plan)", LMP, f"{LMP} + 300", "active", "NULL", "1", "OK")
add("dates", "due_date = lmp_date + 301 (plan)", LMP, f"{LMP} + 301", "active", "NULL", "1", "CK:pregnancy_episodes_dates_check")
add("dates", "due_date = lmp_date + 1 (boundary equivalent)", LMP, f"{LMP} + 1", "active", "NULL", "1", "OK", plan=False)
add("dates", "due_date = lmp_date - 1 (boundary equivalent)", LMP, f"{LMP} - 1", "active", "NULL", "1", "CK:pregnancy_episodes_dates_check", plan=False)
# NOT NULL (plan: lmp_date NULL rejected) + equivalent (due_date NULL)
add("not_null", "lmp_date NULL (plan)", "NULL", DUE, "active", "NULL", "1", "NN:lmp_date")
add("not_null", "due_date NULL (equivalent)", LMP, "NULL", "active", "NULL", "1", "NN:due_date", plan=False)
# expected_count (plan: 0 rejected; 1, 4 accepted; 5 rejected; NULL accepted) + equivalents (2, 3 accepted; -1 rejected)
add("expected_count", "expected_count 0 (plan)", LMP, DUE, "active", "NULL", "0", "CK:pregnancy_episodes_expected_count_check")
add("expected_count", "expected_count 1 (plan)", LMP, DUE, "active", "NULL", "1", "OK")
add("expected_count", "expected_count 4 (plan)", LMP, DUE, "active", "NULL", "4", "OK")
add("expected_count", "expected_count 5 (plan)", LMP, DUE, "active", "NULL", "5", "CK:pregnancy_episodes_expected_count_check")
add("expected_count", "expected_count NULL (plan)", LMP, DUE, "active", "NULL", "NULL", "OK")
add("expected_count", "expected_count 2 (equivalent)", LMP, DUE, "active", "NULL", "2", "OK", plan=False)
add("expected_count", "expected_count 3 (equivalent)", LMP, DUE, "active", "NULL", "3", "OK", plan=False)
add("expected_count", "expected_count -1 (equivalent)", LMP, DUE, "active", "NULL", "-1", "CK:pregnancy_episodes_expected_count_check", plan=False)
# status / ended_at (plan: active+set rejected; given_birth+NULL rejected; paused+NULL accepted; pregnancy_loss+set accepted) + full enum coverage
add("status_ended_at", "active + ended_at set (plan)", LMP, DUE, "active", ENDED, "1", "CK:pregnancy_episodes_ended_at_status_check")
add("status_ended_at", "given_birth + ended_at NULL (plan)", LMP, DUE, "given_birth", "NULL", "1", "CK:pregnancy_episodes_ended_at_status_check")
